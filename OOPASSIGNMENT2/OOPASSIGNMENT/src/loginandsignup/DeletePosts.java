    public void delPosts(String postno,String username,File postsFile) throws FileNotFoundException, IOException{
        File tempFile = new File("postsTempFile.txt");

        BufferedReader reader = new BufferedReader(new FileReader(postsFile));
        BufferedWriter writer = new BufferedWriter(new FileWriter(tempFile));

        String lineToRemove = "Posts #"+postno;
        String currentLine;
        boolean deleteItem = false;

        while((currentLine = reader.readLine()) != null) {
            String trimmedLine = currentLine.trim();
            if(trimmedLine.equals(lineToRemove)){
                deleteItem = true;
            }
            if (deleteItem == true){
                if (trimmedLine.equals("------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------")){
                    deleteItem=false;
                }
            }else{
                System.out.println(currentLine);
                writer.write(currentLine + System.getProperty("line.separator"));
            }
        }
        
        reader.close();
        writer.close();

        if(tempFile.renameTo(new File("posts.txt"))){
            JOptionPane.showMessageDialog(this,"Successfully deleted");
        }else{
            JOptionPane.showMessageDialog(this, "Delete Failed");
        }
        this.setVisible(false);
    }

