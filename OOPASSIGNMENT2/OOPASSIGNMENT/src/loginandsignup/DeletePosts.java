    private void DeleteButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteButtonActionPerformed
        //Get post number and check user name matches then delete post
        String postno = jTextField1.getText();
        
        try {
            boolean found = false;
            File PostsFile = new File("posts.txt");
            Scanner myReader = new Scanner(PostsFile);
            while (myReader.hasNextLine()) {
              String data = myReader.nextLine();
              if (data.equals("Posts #"+postno)){
                  while (myReader.hasNextLine() && found!=true) {
                    String username = myReader.nextLine().toLowerCase();
                    if (username.contains("by:")){
                        found = true;
                        String[] parts = username.split(" ");
                        if(this.getUsername().equals(parts[1])){
                            delPosts(postno,parts[1],PostsFile);
                        }else{
                            JOptionPane.showMessageDialog(this, "That is not your post!");
                        }
                    }
                  }
              }
            }
            myReader.close();
          }catch (FileNotFoundException e) {
            System.out.println("An error occurred.");
            } catch (IOException ex) {
            Logger.getLogger(DeletePosts.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_DeleteButtonActionPerformed

